// Bundles mcp/ui/card.js (with the MCP Apps SDK) into a single self-contained
// HTML string and writes it to mcp/ui/card.generated.js, which the MCP server
// imports. Run via `npm run build` (Vercel runs it on deploy).
import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const uiDir = path.join(here, "..", "mcp", "ui");

const result = await build({
  entryPoints: [path.join(uiDir, "card.js")],
  bundle: true,
  minify: true,
  format: "iife",
  platform: "browser",
  target: ["es2022"],
  write: false,
  legalComments: "none",
});
const js = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const template = await readFile(path.join(uiDir, "card.html"), "utf8");
const html = template.replace("__BUNDLE__", () => js);

const out = `// GENERATED by scripts/build-ui.mjs — do not edit. Source: mcp/ui/card.html + card.js\nexport const CARD_HTML = ${JSON.stringify(html)};\n`;
await writeFile(path.join(uiDir, "card.generated.js"), out);
console.log(`built mcp/ui/card.generated.js (${(html.length / 1024).toFixed(0)} KB)`);
